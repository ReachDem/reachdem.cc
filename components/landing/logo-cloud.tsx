export type LogoName = keyof typeof MARKS

export function LogoCloud({
  title,
  items,
  className,
}: {
  title?: string | null
  items?: { name: LogoName }[] | null
  className?: string
}) {
  const liste = items?.length ? items.map((item) => item.name) : (Object.keys(MARKS) as LogoName[])

  return (
    <section className={cn('px-4 py-8 sm:px-6 sm:py-10', className)}>
      <div className="mx-auto max-w-6xl">
        <p className="text-ink-soft text-center text-[11px] font-medium tracking-[0.14em] uppercase">
          {title ?? 'Sponsored and powered by the best'}
        </p>
        <div className="mt-6 flex flex-wrap items-center justify-center gap-x-10 gap-y-6">
          {liste.map((name) => {
            const mark = MARKS[name]
            if (!mark) return null

            return (
              <span
                key={name}
                title={mark.label}
                className="text-ink-soft/70 hover:text-ink flex items-center gap-2 transition-colors"
              >
                {'textOnly' in mark ? null : (
                <svg
                  viewBox={mark.viewBox}
                  aria-hidden
                  className="size-5 shrink-0 fill-current"
                  xmlns="http://www.w3.org/2000/svg"
                >
                  {mark.paths.map((d, index) => (
                    <path key={index} d={d} />
                  ))}
                </svg>
                )}
                <span className="text-sm font-medium tracking-[-0.01em]">{mark.label}</span>
              </span>
            )
          })}
        </div>
      </div>
    </section>
  )
}
